/** spa-reconcile.mjs — A2 parity reconciliation (token-efficient; runs in Node).
 *  Cross-references each SPA manifest against the platform:
 *   - flows: match the Power Automate workflow GUID in each SPA flow against platform endpoints.config.js
 *     → CAPTURED (endpoint key) or UNCAPTURED (flow the platform has no endpoint for).
 *   - module mapping: provenance-based SPA→module(s).
 *  Emits platform-root/docs/SPA_PARITY_MATRIX.md. Prints a compact summary only. */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const guidOf = (u) => (String(u).match(/workflows\/([0-9a-fA-F]{16,})/) || [])[1] || null;

// --- platform endpoint registry: guid -> KEY ---
const ep = readFileSync('platform-root/config/endpoints.config.js', 'utf8');
const keyRe = /\b([A-Z][A-Z0-9_]+):\s*\{/g;
const keys = []; let m;
while ((m = keyRe.exec(ep))) keys.push({ key: m[1], idx: m.index });
const guidToKey = {};
const urlRe = /PATH\('([0-9a-fA-F]+)'/g;
while ((m = urlRe.exec(ep))) {
  const gi = m.index; let key = null;
  for (const k of keys) { if (k.idx < gi) key = k.key; else break; }
  if (key) guidToKey[m[1].toLowerCase()] = key;
}
const platformGuids = new Set(Object.keys(guidToKey));

// --- SPA -> module(s) (provenance-based; tagged ~ where uncertain) ---
const SPA2MOD = {
  'spa-01': ['correspondence', 'ops-hub', 'registry', 'single-item-ops'], // REGEN DGO live merged hub (broad)
  'spa-02': ['ops-hub', 'bulk-assignment'],
  'spa-03': ['orchestrator'],
  'spa-04': ['executive'],
  'spa-05': ['fasttrack'],
  'spa-06': ['single-item-ops', 'ops-hub'], // Assignment Intelligence Dashboard
  'spa-07': ['bulk-assignment', 'single-item-ops'], // DAA assign-item-direct
  'spa-08': ['stats'],
  'spa-09': ['response-tracking'],
  'spa-10': ['correspondence'],
  'spa-11': ['response-tracking'],
  'spa-12': ['correspondence', 'response-tracking'], // ACK surface
  'spa-13': ['orchestrator'],
  'spa-14': ['reports'],
  'spa-15': ['correspondence'],
  'spa-16': ['registry'],
  'spa-17': ['approvals'],
  'spa-18': ['executive'],
  'spa-19': ['comments'], // static comment report
  'spa-20': ['reports']
};
const platformModules = new Set(readdirSync('platform-root/modules').filter((d) => { try { return readFileSync('platform-root/modules/' + d + '/index.js'); } catch { return false; } }));

// --- walk manifests ---
const files = readdirSync('spa-manifests').filter((f) => /^spa-\d+\.json$/.test(f)).sort();
const rows = []; const uncapturedFlows = []; let totFlows = 0, capFlows = 0;
for (const f of files) {
  const man = JSON.parse(readFileSync('spa-manifests/' + f, 'utf8'));
  const id = man.spa_id;
  const verified = !String(man.purpose).includes('AUTO-DRAFT');
  const mods = SPA2MOD[id] || [];
  const modsOk = mods.every((x) => platformModules.has(x));
  const flows = man.power_automate_flows || [];
  let cap = 0; const un = [];
  for (const fl of flows) {
    const g = guidOf(fl.endpoint_base);
    totFlows++;
    if (g && platformGuids.has(g.toLowerCase())) { cap++; capFlows++; }
    else { un.push({ method: fl.method, guid: g, base: fl.endpoint_base }); }
  }
  for (const u of un) uncapturedFlows.push({ id, file: man.source_filename, ...u });
  rows.push({
    id, file: man.source_filename, verified, mods, modsOk,
    offerings: (man.offerings || []).length, views: (man.views || []).length,
    flows: flows.length, capFlows: cap, unFlows: flows.length - cap
  });
}

// platform endpoints not referenced by any SPA guid (informational)
const spaGuids = new Set();
for (const f of files) { const man = JSON.parse(readFileSync('spa-manifests/' + f, 'utf8')); for (const fl of (man.power_automate_flows || [])) { const g = guidOf(fl.endpoint_base); if (g) spaGuids.add(g.toLowerCase()); } }
const platformOnly = Object.entries(guidToKey).filter(([g]) => !spaGuids.has(g)).map(([, k]) => k);

// --- emit markdown ---
const cov = (r) => r.flows === 0 ? (r.modsOk ? 'n/a (no flows)' : 'CHECK') : (r.capFlows === r.flows ? 'CAPTURED' : (r.capFlows > 0 ? 'PARTIAL' : 'UNCAPTURED'));
let md = `# SPA → Platform Parity Matrix (A2 — flow + module reconciliation)

> Generated by spa-reconcile.mjs. **Flow capture is hard-verified** (Power Automate workflow GUID matched
> against platform/config/endpoints.config.js). **Module mapping** is provenance-based. **Offering/view
> capture is NOT yet verified** here — that is step A3 (enrich the 17 auto-draft manifests, then confirm
> each offering renders in its module via ui-smoke). Manifests tagged "draft" have mechanical fields only.

## Summary
- SPAs: ${rows.length}  |  manifests verified: ${rows.filter((r) => r.verified).length}, auto-draft: ${rows.filter((r) => !r.verified).length}
- SPA flows: ${totFlows}  |  matched to a platform endpoint (by GUID): **${capFlows}**  |  unmatched: **${totFlows - capFlows}**
- Platform endpoints not referenced by any SPA flow: ${platformOnly.length} (${platformOnly.join(', ') || 'none'})

## Per-SPA
| SPA | source | manifest | module(s) | mod ok | offerings | views | flows (cap/total) | flow-capture |
|---|---|---|---|---|---|---|---|---|
`;
for (const r of rows) md += `| ${r.id} | ${r.file} | ${r.verified ? 'verified' : 'draft'} | ${r.mods.join(', ') || '—'} | ${r.modsOk ? '✅' : '⚠️'} | ${r.offerings} | ${r.views} | ${r.capFlows}/${r.flows} | ${cov(r)} |\n`;

md += `\n## Unmatched flows (SPA calls a Power Automate flow the platform registry has no endpoint for)\n`;
if (!uncapturedFlows.length) md += `\n_None — every SPA flow GUID matched a platform endpoint._\n`;
else {
  md += `\n> Each row is a flow GUID present in a SPA but absent from endpoints.config.js. Either (a) the\n> platform consolidated it under a differently-keyed endpoint, (b) it is genuinely UNCAPTURED, or (c) the\n> SPA flow is dead/legacy. A3 confirms which. GUIDs only (no SAS tokens).\n\n| SPA | method | workflow GUID | endpoint_base |\n|---|---|---|---|\n`;
  for (const u of uncapturedFlows) md += `| ${u.id} | ${u.method} | ${u.guid || '—'} | ${(u.base || '').slice(0, 90)} |\n`;
}

md += `\n## Next (A3 / A4)
1. Enrich the auto-draft manifests' **offerings/views/flow shapes** from spa-manifests/_signals/ (cheap) or
   subagents — prioritising SPAs whose flow-capture is PARTIAL/UNCAPTURED or whose module mapping is ⚠️.
2. For each offering, confirm a corresponding feature exists in the mapped module (ui-smoke or read);
   mark CAPTURED / PARTIAL / UNCAPTURED at the feature level.
3. Close unblocked UNCAPTURED/PARTIAL features (gate + ui-smoke); log blocked ones in REGISTER_RECONCILIATION.md.
`;
writeFileSync('platform-root/docs/SPA_PARITY_MATRIX.md', md);

console.log('flows total=' + totFlows + ' captured=' + capFlows + ' unmatched=' + (totFlows - capFlows));
console.log('platform endpoints unused-by-spa: ' + (platformOnly.join(',') || 'none'));
console.log('module-mapping warnings: ' + rows.filter((r) => !r.modsOk).map((r) => r.id).join(',') || 'none');
console.log('per-spa flow-capture: ' + rows.map((r) => r.id + '=' + (r.flows ? r.capFlows + '/' + r.flows : '0')).join(' '));
console.log('wrote platform-root/docs/SPA_PARITY_MATRIX.md');
